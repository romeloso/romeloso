import type { LessonDefinition, ReadingComprehensionActivity, ReadingGenre } from '@/types'

const choice = (value: string) => ({ id: value, label: value, value })

function q(
  id: string,
  passageTitle: string,
  passage: string,
  genre: ReadingGenre,
  prompt: string,
  answer: string,
  options: string[],
): ReadingComprehensionActivity {
  return {
    id,
    kind: 'reading_comprehension',
    prompt,
    passageTitle,
    passage,
    genre,
    options: options.map(choice),
    answer,
  }
}

function lesson(
  id: string,
  levelId: string,
  title: string,
  genre: ReadingGenre,
  minGrade: number,
  maxGrade: number,
  minAge: number,
  maxAge: number,
  activities: ReadingComprehensionActivity[],
): LessonDefinition {
  return {
    id,
    gameId: 'reading',
    levelId,
    title,
    genre,
    minGrade,
    maxGrade,
    minAge,
    maxAge,
    source: 'builtin',
    activities,
  }
}

