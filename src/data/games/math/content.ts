import type { LessonDefinition, MathChoiceActivity } from '@/types'

const choice = (value: string) => ({ id: value, label: value, value })

function math(
  id: string,
  prompt: string,
  expression: string,
  answer: string,
  options: string[],
): MathChoiceActivity {
  return {
    id,
    kind: 'math_choice',
    prompt,
    expression,
    answer,
    options: options.map(choice),
  }
}

